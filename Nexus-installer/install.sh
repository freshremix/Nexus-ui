
cat > /root/Nexus-ui/Nexus-installer/install-v3.sh <<'SCRIPT'
#!/usr/bin/env bash
set -Eeuo pipefail
umask 077

BASE="/root/.nexus-pro-deploy"
STATE="$BASE/state.env"
CF="/root/Argo/cloudflared"
CERT="/root/.cloudflared/cert.pem"
DEFAULT_PROJECT="/root/Nexus-ui"
DEFAULT_PORT="9127"
DEFAULT_DOMAIN="spot4u.ir"
DEFAULT_SUB="nxpr"
DEFAULT_TUNNEL="nexus-pro-panel"

info(){ echo "[INFO] $*"; }
warn(){ echo "[WARN] $*" >&2; }
die(){ echo "[ERROR] $*" >&2; exit 1; }

for cmd in curl python3; do
  command -v "$cmd" >/dev/null || die "Required command missing: $cmd"
done
[ -x "$CF" ] || die "cloudflared executable not found: $CF"

api() {
  local method="$1" url="$2" data="${3-}"
  if [ -n "$data" ]; then
    curl -fsS --connect-timeout 10 --max-time 30 \
      -X "$method" \
      -H "Authorization: Bearer $TOKEN" \
      -H "Content-Type: application/json" \
      --data "$data" "$url"
  else
    curl -fsS --connect-timeout 10 --max-time 30 \
      -X "$method" \
      -H "Authorization: Bearer $TOKEN" "$url"
  fi
}

api_ok() {
  python3 -c 'import json,sys; d=json.load(sys.stdin); print(d.get("result",{}).get("id","") if isinstance(d.get("result"),dict) else ""); sys.exit(0 if d.get("success") else 1)'
}

get_zone() {
  local response
  response="$(api GET "https://api.cloudflare.com/client/v4/zones?name=$DOMAIN&status=active")" ||
    die "Cloudflare API failed. Check token and network."
  ZONE_ID="$(printf '%s' "$response" | python3 -c '
import json,sys
d=json.load(sys.stdin)
if not d.get("success"): sys.exit(2)
r=d.get("result",[])
print(r[0]["id"] if len(r)==1 else "")
')" || true
  [ -n "${ZONE_ID:-}" ] ||
    die "Active zone '$DOMAIN' was not found uniquely in this account. No tunnel or DNS changes made."
  info "Verified active Cloudflare zone: $DOMAIN"
}

ask_token() {
  printf 'Cloudflare API Token (input hidden): '
  read -r -s TOKEN
  echo
  [ -n "$TOKEN" ] || die "Token is required."
  local v
  v="$(api GET "https://api.cloudflare.com/client/v4/user/tokens/verify")" ||
    die "Token verification request failed."
  printf '%s' "$v" | python3 -c '
import json,sys
d=json.load(sys.stdin)
sys.exit(0 if d.get("success") and d.get("result",{}).get("status")=="active" else 1)
' || die "Token is invalid or inactive."
}

load_state() {
  [ -f "$STATE" ] || return 1
  # State file is generated by this script and permissions are restricted.
  source "$STATE"
  return 0
}

save_state() {
  mkdir -p "$BASE"
  chmod 700 "$BASE"
  cat > "$STATE" <<EOF
PROJECT=$(printf '%q' "$PROJECT")
PORT=$(printf '%q' "$PORT")
DOMAIN=$(printf '%q' "$DOMAIN")
SUB=$(printf '%q' "$SUB")
HOSTNAME=$(printf '%q' "$HOSTNAME")
TUNNEL=$(printf '%q' "$TUNNEL")
TUNNEL_ID=$(printf '%q' "$TUNNEL_ID")
ZONE_ID=$(printf '%q' "$ZONE_ID")
CONFIG=$(printf '%q' "$CONFIG")
CRED=$(printf '%q' "$CRED")
PIDFILE=$(printf '%q' "$PIDFILE")
LOG=$(printf '%q' "$LOG")
EOF
  chmod 600 "$STATE"
}

install_panel() {
  PROJECT="${PROJECT:-$DEFAULT_PROJECT}"
  read -r -p "Nexus project path [$PROJECT]: " v
  PROJECT="${v:-$PROJECT}"
  [ -d "$PROJECT" ] || die "Project directory not found: $PROJECT"

  PORT="$DEFAULT_PORT"
  read -r -p "Panel local port [$PORT]: " v
  PORT="${v:-$PORT}"
  [[ "$PORT" =~ ^[0-9]+$ ]] && [ "$PORT" -ge 1 ] && [ "$PORT" -le 65535 ] ||
    die "Invalid port."

  DOMAIN="$DEFAULT_DOMAIN"
  read -r -p "Root domain [$DOMAIN]: " v
  DOMAIN="${v:-$DOMAIN}"
  DOMAIN="${DOMAIN,,}"
  [[ "$DOMAIN" =~ ^([a-z0-9-]+\.)+[a-z]{2,}$ ]] || die "Invalid root domain."

  SUB="$DEFAULT_SUB"
  read -r -p "Subdomain label only [$SUB]: " v
  SUB="${v:-$SUB}"
  [[ "$SUB" =~ ^[a-z0-9-]+$ ]] || die "Enter only the subdomain label, e.g. nxpr."

  TUNNEL="$DEFAULT_TUNNEL"
  read -r -p "Tunnel name [$TUNNEL]: " v
  TUNNEL="${v:-$TUNNEL}"
  [[ "$TUNNEL" =~ ^[a-zA-Z0-9_-]+$ ]] || die "Invalid tunnel name."
  HOSTNAME="$SUB.$DOMAIN"

  CONFIG="$BASE/cloudflared/$TUNNEL.yml"
  CRED=""
  PIDFILE="$BASE/cloudflared-$TUNNEL.pid"
  LOG="$BASE/logs/cloudflared-$TUNNEL.log"

  ask_token
  get_zone

  # Do not overwrite any existing DNS record.
  dns="$(api GET "https://api.cloudflare.com/client/v4/zones/$ZONE_ID/dns_records?name=$HOSTNAME")" ||
    die "Could not check DNS records."
  count="$(printf '%s' "$dns" | python3 -c 'import json,sys; d=json.load(sys.stdin); print(len(d.get("result",[])) if d.get("success") else -1)')"
  [ "$count" = "0" ] || die "DNS record for $HOSTNAME already exists (or lookup failed). Inspect it in Cloudflare DNS first; no record was overwritten."

  # Avoid creating a duplicate tunnel.
  list="$("$CF" tunnel list 2>&1)" || die "Cannot list existing tunnels: $list"
  if printf '%s\n' "$list" | grep -Eq "[[:space:]]$TUNNEL[[:space:]]"; then
    die "Tunnel '$TUNNEL' already exists but is not tracked by this script. Inspect it before proceeding."
  fi

  mkdir -p "$BASE/cloudflared" "$BASE/logs"
  chmod 700 "$BASE" "$BASE/cloudflared" "$BASE/logs"

  info "Creating tunnel..."
  "$CF" tunnel create "$TUNNEL" 2>&1 | tee "$BASE/logs/tunnel-create.log"

  TUNNEL_ID="$(python3 - "$BASE/logs/tunnel-create.log" <<'PY'
import re,sys
s=open(sys.argv[1],errors="ignore").read()
m=re.search(r'Created tunnel .* with id ([0-9a-f-]{36})',s,re.I)
print(m.group(1) if m else "")
PY
)"
  [[ "$TUNNEL_ID" =~ ^[0-9a-fA-F-]{36}$ ]] ||
    die "Could not determine tunnel ID. Check $BASE/logs/tunnel-create.log"

  CRED="/root/.cloudflared/$TUNNEL_ID.json"
  [ -f "$CRED" ] || die "Tunnel credential file not found: $CRED"

  # Save state immediately so a later failure can be cleaned up.
  save_state

  cat > "$CONFIG" <<EOF
tunnel: $TUNNEL_ID
credentials-file: $CRED
no-autoupdate: true

ingress:
  - hostname: $HOSTNAME
    service: http://127.0.0.1:$PORT
  - service: http_status:404
EOF
  chmod 600 "$CONFIG"

  # Add only the exact requested record in the verified zone.
  target="$TUNNEL_ID.cfargotunnel.com"
  body="$(python3 - "$HOSTNAME" "$target" <<'PY'
import json,sys
print(json.dumps({"type":"CNAME","name":sys.argv[1],"content":sys.argv[2],"proxied":True,"ttl":1}))
PY
)"
  result="$(api POST "https://api.cloudflare.com/client/v4/zones/$ZONE_ID/dns_records" "$body")" ||
    die "DNS API request failed. State was retained for cleanup."
  printf '%s' "$result" | python3 -c '
import json,sys
d=json.load(sys.stdin)
if not d.get("success"):
 print(json.dumps(d.get("errors",[]),ensure_ascii=False),file=sys.stderr)
 sys.exit(1)
' || die "Cloudflare rejected the DNS record. State was retained."

  save_state

  info "Checking local panel..."
  curl -fsS --max-time 5 "http://127.0.0.1:$PORT/" >/dev/null ||
    die "Panel did not respond locally at port $PORT. DNS and tunnel state were retained."

  info "Starting Cloudflare tunnel..."
  nohup "$CF" tunnel --config "$CONFIG" run "$TUNNEL_ID" \
    >>"$LOG" 2>&1 </dev/null &
  echo $! > "$PIDFILE"
  chmod 600 "$PIDFILE"
  save_state

  sleep 3
  if ! kill -0 "$(cat "$PIDFILE")" 2>/dev/null; then
    die "Tunnel process stopped. Check $LOG. State was retained for cleanup."
  fi

  echo
  info "Install commands completed."
  echo "Panel URL: https://$HOSTNAME"
  echo "Tunnel ID: $TUNNEL_ID"
  echo "Config: $CONFIG"
  echo "Log: $LOG"
  echo "State: $STATE"
}

cleanup() {
  if ! load_state; then
    warn "No saved state at $STATE."
    warn "No automatic deletion will be attempted; this avoids touching unrelated resources."
    warn "If an older untracked tunnel exists, inspect it manually before deleting it."
    return
  fi

  echo "This cleanup targets only the saved deployment:"
  echo "  Tunnel: ${TUNNEL:-unknown} (${TUNNEL_ID:-unknown})"
  echo "  Hostname: ${HOSTNAME:-unknown}"
  read -r -p "Type DELETE to continue: " confirm
  [ "$confirm" = "DELETE" ] || { info "Cancelled."; return; }

  ask_token
  get_zone

  if [ -n "${PIDFILE:-}" ] && [ -f "$PIDFILE" ]; then
    pid="$(cat "$PIDFILE")"
    if [[ "$pid" =~ ^[0-9]+$ ]] && [ "$pid" -gt 1 ]; then
      kill "$pid" 2>/dev/null || true
    fi
  fi

  # Delete DNS only if it is the CNAME pointing to this deployment's tunnel.
  if [ -n "${TUNNEL_ID:-}" ] && [ -n "${HOSTNAME:-}" ]; then
    target="$TUNNEL_ID.cfargotunnel.com"
    dns="$(api GET "https://api.cloudflare.com/client/v4/zones/$ZONE_ID/dns_records?name=$HOSTNAME")" ||
      die "DNS lookup failed; refusing further deletion."
    record="$(printf '%s' "$dns" | python3 - "$target" <<'PY'
import json,sys
target=sys.argv[1]
d=json.load(sys.stdin)
for r in d.get("result",[]):
 if r.get("type")=="CNAME" and r.get("content","").rstrip(".").lower()==target.lower():
  print(r.get("id",""))
  break
PY
)"
    if [ -n "$record" ]; then
      api DELETE "https://api.cloudflare.com/client/v4/zones/$ZONE_ID/dns_records/$record" >/dev/null ||
        die "Could not delete the matching DNS record."
      info "Deleted matching DNS record."
    else
      info "No matching tunnel CNAME found; no DNS record deleted."
    fi
  fi

  # Refuse to delete the protected legacy tunnel.
  [ "${TUNNEL:-}" != "argo02" ] || die "Safety stop: argo02 is protected."
  if [ -n "${TUNNEL_ID:-}" ]; then
    "$CF" tunnel delete "$TUNNEL_ID" ||
      warn "Tunnel deletion failed; inspect it manually."
  fi

  [ -n "${CRED:-}" ] && rm -f -- "$CRED"
  [ -n "${CONFIG:-}" ] && rm -f -- "$CONFIG"
  [ -n "${PIDFILE:-}" ] && rm -f -- "$PIDFILE"
  [ -n "${LOG:-}" ] && rm -f -- "$LOG"
  rm -f -- "$STATE"
  info "Saved deployment resources cleaned up."
}

echo
echo "NEXUS PRO — SPRITE DEPLOYMENT MANAGER v3"
echo "1) Install"
echo "2) Cleanup saved deployment"
echo "3) Exit"
read -r -p "Choose (1-3): " choice
case "$choice" in
  1) install_panel ;;
  2) cleanup ;;
  3) exit 0 ;;
  *) die "Invalid choice." ;;
esac
SCRIPT

chmod 700 /root/Nexus-ui/Nexus-installer/install-v3.sh
bash -n /root/Nexus-ui/Nexus-installer/install-v3.sh
echo "Script syntax check passed."
